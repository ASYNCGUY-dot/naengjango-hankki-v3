-- V3 (2026-09-15): 같은 사람이 같은 레시피를 한순간에 두 번 연 기록을 막는다
--
-- 배경
-- 운영 recipe_view 25건 중 2쌍이 같은 사람·같은 레시피로 15ms, 48ms 간격을 두고 찍혀
-- 있었다. 사람이 누를 수 있는 간격이 아니고, Phase 4의 "무엇을 실제로 열어봤나"가
-- 그만큼(8%) 부풀려진다.
--
-- 원인은 확정하지 못했다. 두 쌍 모두 직전 활동으로부터 약 10분 뒤라 "쉬고 나면 첫
-- 요청이 느려서 사용자가 새로고침했다"를 의심했는데, 배포 API를 11분 쉬게 한 뒤 재보니
-- 첫 요청이 웜 상태와 같았다(DB 경로 0.95초 대 0.66~0.93초). 그 가설은 틀렸다.
-- 프론트에는 재시도가 없고, 상세 화면은 레시피 번호가 바뀔 때만 요청하며, 로그인 상태도
-- 로딩 중에 바뀌지 않는다.
--
-- 왜 조회-후-삽입이 아니라 제약인가
-- 두 기록이 15ms 간격이라는 건 두 요청이 **동시에** 처리됐다는 뜻이다. "먼저 있는지
-- 보고 없으면 넣기"는 서로 커밋 전이라 둘 다 "없다"를 보고 둘 다 넣는다 - 정확히 지금
-- 일어난 일이다. 원인과 무관하게 막으려면 DB가 강제해야 한다.
--
-- 규칙
-- 로그인한 사람의 recipe_view만, 10초 단위 구간 안에서 (사람, 레시피)당 한 줄.
-- 비로그인은 묶지 않는다 - user_id가 NULL이라 서로 다른 방문자를 구분할 수 없고,
-- 공유 링크 유입은 이 테스트에서 드문 만큼 한 줄 한 줄이 중요하다.
-- 구간 경계에 걸리면 수십 ms 간격도 두 줄이 될 수 있다(10초 중 수십 ms라 드물다).
--
-- 기존 행은 건드리지 않는다. 새 컬럼이 NULL이라 제약 대상에서 빠진다. 이미 찍힌 두 쌍은
-- 지우지 않고 분석 쿼리에서 걸러 본다(docs/PHASE4_지인테스트.md).
--
-- 적용 순서: 이 파일을 먼저 적용한 뒤 코드를 배포한다. 컬럼이 없는 DB에 새 코드가 가면
-- 기록 INSERT가 실패하고(요청은 SAVEPOINT 덕분에 살지만) 그동안의 로그가 전부 빠진다.
-- 반대로 컬럼만 먼저 생기는 것은 기존 코드에 아무 영향이 없다.
--
-- 사용법: 011 다음에 적용한다.

BEGIN;

ALTER TABLE usage_events ADD COLUMN IF NOT EXISTS dedupe_bucket BIGINT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_usage_events_recipe_view_dedupe
    ON usage_events (user_id, recipe_id, dedupe_bucket)
    WHERE event = 'recipe_view' AND dedupe_bucket IS NOT NULL;

COMMIT;
