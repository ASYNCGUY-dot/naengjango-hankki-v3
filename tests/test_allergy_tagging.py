@pytest.mark.parametrize(
    "text,allergen",
    [
        # 과잉 차단도 해롭다. 먹을 수 있는 것을 계속 빼면 사용자가 알레르기 입력을
        # 지워버리고, 그러면 진짜 위험한 것도 안 걸러진다.
        ("쌀국수 100g", "밀"),
        ("곤약면 200g", "밀"),
        ("땅콩버터 1큰술", "우유"),
        ("땅콩가루 2큰술", "대두"),
        ("멍게살 100g", "게"),
        # 2026-08-22에 추가. 이름 매칭 쪽에도 같은 모양의 오탐이 있었다.
        ("돼지감자가루 1/4컵", "돼지고기"),   # 뚱딴지, 고기가 아니다
        ("돼지호박 50g", "돼지고기"),         # 애호박
        ("우삼겹 50g", "돼지고기"),           # 소고기다
        ("땅콩호박 타르트용 200g", "땅콩"),   # 단호박 품종
        ("굴림만두 5개", "굴"),
        ("겨잣가루 5g", "잣"),
        ("코코넛밀크 200ml", "밀"),
        # "박력 쌀가루"·"강력 쌀가루"는 쌀가루다. 그래서 파생어를 "박력분"까지 붙여 좁혔다.
        ("박력 쌀가루 100g", "밀"),
        ("강력 쌀가루 60g", "밀"),
    ],
)
def test_lookalikes_are_not_tagged(text, allergen):
    assert allergen not in tag_allergy(text)


@pytest.mark.parametrize("text", ["메밀면 100g", "메밀가루 1컵", "오트밀 50g"])
def test_buckwheat_and_oats_keep_the_wheat_tag(text):
    """이름에 "밀"이 들어갈 뿐이지만 일부러 태그를 남긴다.

    시판 메밀면·막국수는 밀가루를 섞는 경우가 많고 오트밀은 밀과 같은 설비를 쓰는 일이
    잦다. 이름만 보고 떼면 밀 알레르기가 있는 사람의 보호가 실제로 사라진다.
    과잉 차단은 불편이지만 과소 차단은 위험이라 확실하지 않은 쪽은 남긴다.
    """
    assert "밀" in tag_allergy(text)


def test_pork_and_beef_are_not_confused():
    """부위 이름만 보고 축종을 섞으면 안 된다.

    "우삼겹"에는 "삼겹"이 들어 있고 "닭안심살"에는 "안심"이 들어 있다. 그래서 부위
    이름 중 축종이 갈리는 것(안심·등심·갈비·사태)은 아예 파생어로 쓰지 않는다.
    """
    assert tag_allergy("우삼겹 50g") == ["소고기"]
    assert "돼지고기" not in tag_allergy("닭안심살 200g")
    assert "소고기" not in tag_allergy("닭안심살 200g")


